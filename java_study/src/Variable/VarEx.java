package Variable;

public class VarEx {
    public static void main(String[] args) {
        /*
        * 변수(Variable)
        * 정의: 프로그램이 실행 하는 동안 데이터를 저장하기 위한 메모리 공간
        *
        * 왜 사용하는가?
        * ㄴ 데이터를 저장하기 위해
        * ㄴ 저장한 데이터를 꺼내서 사용하기 위해
        * ㄴ 값을 변경하기 위해
        * 변수가 없다면 일일히 같은 값을 계속 직접 입력 해야한다.
        *
        * 언제 사용하는가?
        * ㄴ 사용자의 입력을 저장하기 위해
        * ㄴ 계산 결과를 저장하기 위해
        * ㄴ 반복문에 값을 변경하기 위해
        * ㄴ 객체를 저장할 때
        *
        * 문법
        * ㄴ 변수타입 변수명 = 값;
        *
        * 주의사항
        * ㄴ 예약어는 사용할 수 없다.
        * ㄴ 같은 이름으로 다시 선언할 수 없다.
        * */

        // 변수 연습
        String date = "2026/07/13";
        System.out.println(date);
        date = "2026/07/14";
        System.out.println(date);

        // 참조형
    }
}
